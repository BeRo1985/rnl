/******************************************************************************
 *                       RNL CONTINUATION ALIGNMENT CHECK                     *
 ******************************************************************************
 *                                                                            *
 * Checks the alignment of continuation lines in the Pascal sources of RNL.   *
 *                                                                            *
 * RNL lines up the continuation of an unclosed parenthesis with the first    *
 * character after that parenthesis:                                          *
 *                                                                            *
 *     procedure WriteLongMessageHeader(const aData:TRNLPointer;              *
 *                                      const aMessageNumber:TRNLUInt16;      *
 *                                      const aOffset,aLength:TRNLUInt32);    *
 *                                                                            *
 *     result:=fPeer.fMTU-(RNL_IP_HEADER_SIZE+                                *
 *                         RNL_UDP_HEADER_SIZE+                               *
 *                         SizeOf(TRNLProtocolNormalPacketHeader));           *
 *                                                                            *
 * Getting this wrong by a single space is easy to do and hard to see in      *
 * review, which is why it is worth checking mechanically.                    *
 *                                                                            *
 * A baseline file records the deviations which already exist, so that only   *
 * newly introduced ones are reported. Without it the pre-existing ones would *
 * drown out everything new.                                                  *
 *                                                                            *
 * Plain C and nothing else on purpose: this is a tool inside a repository    *
 * which depends on nothing, and a checker that drags in an interpreter would *
 * be a dependency of its own.                                                *
 *                                                                            *
 * Build:                                                                     *
 *   cd src/tests && cc -O2 -o checkalignment checkalignment.c                *
 *                                                                            *
 * Usage:                                                                     *
 *   ./checkalignment                   check, report new deviations          *
 *   ./checkalignment --all             report every deviation, baseline too  *
 *   ./checkalignment --write-baseline  accept the current state as baseline  *
 *   ./checkalignment FILE...           check the given files instead         *
 *                                                                            *
 * Exit codes: 0 nothing new, 1 new deviations found, 2 usage or file error.  *
 *                                                                            *
 * A file named on the command line is reported under the name it was given.  *
 * The default run, which is the one the baseline is keyed on, is unaffected: *
 * there the names come from the list above either way.                       *
 *                                                                            *
 ******************************************************************************/

